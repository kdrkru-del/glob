const storageKey = "globerion-language";

const getStoredLanguage = () => {
  try {
    return localStorage.getItem(storageKey);
  } catch {
    return null;
  }
};

const setStoredLanguage = (language) => {
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    return null;
  }
};

const pageName = document.body.dataset.page || "home";
const descriptionMeta = document.querySelector('meta[name="description"]');
const languageButtons = document.querySelectorAll("[data-lang]");
const navigation = document.querySelector(".nav");
const navigationToggle = document.querySelector(".nav-toggle");
const navigationSubmenus = document.querySelectorAll("[data-mobile-submenu]");

const translate = (language, key) => {
  return translations[language]?.[key] || translations.en?.[key] || "";
};

const updateNavigationToggleLabel = (isOpen) => {
  if (!navigationToggle) {
    return;
  }

  const key = isOpen ? "aria.menu.close" : "aria.menu.open";
  const currentLanguage = document.documentElement.lang || "en";
  navigationToggle.dataset.i18nAriaLabel = key;
  navigationToggle.setAttribute("aria-label", translate(currentLanguage, key));
};

const applyLanguage = (language) => {
  const currentLanguage = translations[language] ? language : "en";
  const title = translate(currentLanguage, `meta.${pageName}.title`);
  const description = translate(currentLanguage, `meta.${pageName}.description`);

  document.documentElement.lang = currentLanguage;

  if (title) {
    document.title = title;
  }

  if (description) {
    descriptionMeta?.setAttribute("content", description);
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const text = translate(currentLanguage, element.dataset.i18n);

    if (text) {
      element.textContent = text;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const text = translate(currentLanguage, element.dataset.i18nPlaceholder);

    if (text) {
      element.setAttribute("placeholder", text);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const text = translate(currentLanguage, element.dataset.i18nAlt);

    if (text) {
      element.setAttribute("alt", text);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const text = translate(currentLanguage, element.dataset.i18nAriaLabel);

    if (text) {
      element.setAttribute("aria-label", text);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  document.querySelectorAll(".form-note").forEach((note) => {
    note.textContent = "";
  });

  setStoredLanguage(currentLanguage);
};

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});

const closeNavigationSubmenus = () => {
  navigationSubmenus.forEach((submenu) => {
    submenu.classList.remove("is-open");
    submenu.querySelector(".nav-submenu-toggle")?.setAttribute("aria-expanded", "false");
    submenu.querySelector(".nav-submenu-panel")?.removeAttribute("style");
  });
};

navigationSubmenus.forEach((submenu) => {
  const submenuToggle = submenu.querySelector(".nav-submenu-toggle");
  const submenuPanel = submenu.querySelector(".nav-submenu-panel");

  submenuToggle?.addEventListener("click", () => {
    const willOpen = !submenu.classList.contains("is-open");
    closeNavigationSubmenus();

    if (willOpen) {
      submenu.classList.add("is-open");
      submenuToggle.setAttribute("aria-expanded", "true");
      submenuPanel?.style.setProperty("visibility", "visible");
      submenuPanel?.style.setProperty("opacity", "1");
      submenuPanel?.style.setProperty("transform", "translateY(0)");
    }
  });
});

navigationToggle?.addEventListener("click", () => {
  const isOpen = navigation.classList.toggle("is-open");
  navigationToggle.setAttribute("aria-expanded", String(isOpen));
  updateNavigationToggleLabel(isOpen);

  if (!isOpen) {
    closeNavigationSubmenus();
  }
});

navigation?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navigation.classList.remove("is-open");
    navigationToggle?.setAttribute("aria-expanded", "false");
    updateNavigationToggleLabel(false);
    closeNavigationSubmenus();
  });
});

document.querySelectorAll("[data-year]").forEach((element) => {
  element.textContent = new Date().getFullYear();
});

document.querySelectorAll(".request-form").forEach((form) => {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const currentLanguage = document.documentElement.lang || "ru";
    const note = form.querySelector(".form-note");

    if (note) {
      note.textContent = translate(currentLanguage, "form.note");
    }

    form.reset();
  });
});

const revealItems = document.querySelectorAll("[data-reveal]");

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.14 });

  revealItems.forEach((item) => revealObserver.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

