const syncMarketEntryFields = (form) => {
  const category = form.querySelector('select[name="category"]');
  const fields = form.querySelector("[data-market-entry-fields]");

  if (!category || !fields) {
    return;
  }

  const isBuyerSearch = category.value === buyerSearchCategory;
  fields.hidden = !isBuyerSearch;

  fields.querySelectorAll("[data-market-entry-required]").forEach((field) => {
    field.required = isBuyerSearch;
  });
};

document.querySelectorAll(".request-form").forEach((form) => {
  const category = form.querySelector('select[name="category"]');
  const requestedCategory = new URLSearchParams(window.location.search).get("category");

  if (category && requestCategories.has(requestedCategory)) {
    const requestedOption = category.querySelector(`option[value="${requestedCategory}"]`);

    if (requestedOption) {
      category.value = requestedCategory;
    }
  }

  syncMarketEntryFields(form);
  category?.addEventListener("change", () => syncMarketEntryFields(form));

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const currentLanguage = document.documentElement.lang || "ru";
    const note = form.querySelector(".form-note");

    if (note) {
      note.textContent = translate(currentLanguage, "form.note");
    }

    form.reset();
    syncMarketEntryFields(form);
  });
});

